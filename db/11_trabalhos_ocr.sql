CREATE TABLE IF NOT EXISTS trabalhos_ocr (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anexo_id integer NOT NULL UNIQUE REFERENCES anexos_despesa(id) ON DELETE CASCADE,
    estado text NOT NULL DEFAULT 'PENDENTE'
        CHECK (estado IN ('PENDENTE', 'PROCESSANDO', 'CONCLUIDO', 'FALHOU')),
    tentativas integer NOT NULL DEFAULT 0,
    reserva uuid,
    reserva_ate timestamptz,
    resultado jsonb,
    criado_em timestamptz NOT NULL DEFAULT now(),
    atualizado_em timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS trabalhos_ocr_fila_idx
    ON trabalhos_ocr (criado_em, id) WHERE estado IN ('PENDENTE', 'PROCESSANDO');
